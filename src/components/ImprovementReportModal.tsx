import React from 'react';
import { X, AlertCircle, CheckCircle2, BookOpen, Lightbulb, Printer, Trophy } from 'lucide-react';
import { ImprovementReport } from '../types/student';

interface ImprovementReportModalProps {
  isOpen: boolean;
  onClose: () => void;
  report: ImprovementReport | null;
  loading: boolean;
}

export const ImprovementReportModal: React.FC<ImprovementReportModalProps> = ({
  isOpen,
  onClose,
  report,
  loading,
}) => {
  if (!isOpen) return null;

  const handlePrint = () => {
    window.print();
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-slate-950/60 backdrop-blur-sm overflow-y-auto">
      <div className="relative w-full max-w-2xl rounded-2xl bg-white shadow-2xl border border-slate-200 overflow-hidden my-8 print:shadow-none print:border-none print:m-0 print:max-w-none">
        {/* Header */}
        <div className="flex items-center justify-between border-b border-slate-100 bg-slate-50/80 px-6 py-4">
          <div className="flex items-center gap-3">
            <div className="flex h-10 w-10 items-center justify-center rounded-xl bg-blue-100 text-blue-700">
              <BookOpen className="h-5 w-5" />
            </div>
            <div>
              <h2 className="text-lg font-bold text-slate-900">
                Official Subject Improvement Report
              </h2>
              <p className="text-xs text-slate-500">
                Generated by C++ backend engine for student #{report?.studentId || '...'}
              </p>
            </div>
          </div>
          <button
            onClick={onClose}
            className="rounded-lg p-1.5 text-slate-400 hover:bg-slate-200/60 hover:text-slate-700 print:hidden"
          >
            <X className="h-5 w-5" />
          </button>
        </div>

        {/* Content */}
        <div className="p-6">
          {loading ? (
            <div className="flex flex-col items-center justify-center py-12 text-slate-500">
              <div className="h-8 w-8 animate-spin rounded-full border-3 border-indigo-600 border-t-transparent" />
              <p className="mt-3 text-xs">Querying C++ backend for improvement analysis...</p>
            </div>
          ) : !report ? (
            <div className="py-8 text-center text-slate-500">
              <AlertCircle className="mx-auto h-8 w-8 text-slate-400" />
              <p className="mt-2 text-sm">No report available for this student.</p>
            </div>
          ) : (
            <div className="space-y-6">
              {/* Student Overview Header Card */}
              <div className="rounded-xl border border-slate-200 bg-gradient-to-r from-slate-50 to-indigo-50/30 p-4">
                <div className="flex flex-col sm:flex-row sm:items-center sm:justify-between gap-3">
                  <div>
                    <span className="font-mono text-xs font-bold text-blue-600">
                      ID: #{report.studentId}
                    </span>
                    <h3 className="text-xl font-extrabold text-slate-900">
                      {report.studentName}
                    </h3>
                  </div>

                  <div className="flex items-center gap-4 text-center">
                    <div>
                      <div className="text-[10px] uppercase font-semibold text-slate-400">Total Marks</div>
                      <div className="text-base font-bold text-slate-800 font-mono">
                        {report.totalMarks} / 500
                      </div>
                    </div>
                    <div className="h-8 w-px bg-slate-200" />
                    <div>
                      <div className="text-[10px] uppercase font-semibold text-slate-400">Percentage</div>
                      <div className="text-base font-bold text-blue-600 font-mono">
                        {report.percentage}%
                      </div>
                    </div>
                    <div className="h-8 w-px bg-slate-200" />
                    <div>
                      <div className="text-[10px] uppercase font-semibold text-slate-400">Grade</div>
                      <span className="inline-block px-2.5 py-0.5 rounded text-sm font-black bg-indigo-100 text-indigo-800">
                        {report.grade}
                      </span>
                    </div>
                  </div>
                </div>
              </div>

              {/* Status Banner */}
              {report.needsImprovement ? (
                <div className="rounded-xl border border-rose-200 bg-rose-50/80 p-4">
                  <div className="flex items-start gap-3">
                    <AlertCircle className="h-5 w-5 text-rose-600 shrink-0 mt-0.5" />
                    <div>
                      <h4 className="text-sm font-bold text-rose-900">
                        Academic Improvement Alert Required
                      </h4>
                      <p className="mt-1 text-xs text-rose-700 leading-relaxed font-mono">
                        {report.summary}
                      </p>
                      <p className="mt-1 text-[11px] text-rose-600">
                        The student scored below the college minimum proficiency threshold of 60.0 marks in {report.weakSubjectsCount} subject(s). Targeted academic mentoring is required.
                      </p>
                    </div>
                  </div>
                </div>
              ) : (
                <div className="rounded-xl border border-emerald-200 bg-emerald-50/80 p-4">
                  <div className="flex items-center gap-3">
                    <CheckCircle2 className="h-6 w-6 text-emerald-600 shrink-0" />
                    <div>
                      <h4 className="text-sm font-bold text-emerald-900">
                        Proficient in All Curriculum Subjects!
                      </h4>
                      <p className="mt-0.5 text-xs text-emerald-700">
                        {report.summary}
                      </p>
                    </div>
                  </div>
                </div>
              )}

              {/* Weak Subjects Cards */}
              {report.weakSubjects && report.weakSubjects.length > 0 && (
                <div>
                  <h4 className="text-xs font-bold uppercase tracking-wider text-slate-700 mb-3 flex items-center gap-1.5">
                    <AlertCircle className="h-4 w-4 text-rose-500" />
                    Subjects Requiring Immediate Attention (&lt; 60 Marks)
                  </h4>
                  <div className="space-y-3">
                    {report.weakSubjects.map((w) => (
                      <div
                        key={w.subject}
                        className="rounded-xl border border-rose-200 bg-white p-4 shadow-2xs"
                      >
                        <div className="flex items-center justify-between">
                          <div className="flex items-center gap-2">
                            <span className="font-bold text-sm text-slate-900">{w.subject}</span>
                            <span className="rounded bg-rose-100 px-2 py-0.5 text-[11px] font-bold text-rose-800 font-mono">
                              {w.mark} / 100
                            </span>
                          </div>
                          <span className="text-xs font-semibold text-rose-700 font-mono">
                            Shortfall: -{w.shortfall} pts
                          </span>
                        </div>

                        {/* Progress bar to 60 */}
                        <div className="mt-2.5 h-2 w-full overflow-hidden rounded-full bg-slate-100">
                          <div
                            className="h-full rounded-full bg-rose-500"
                            style={{ width: `${w.mark}%` }}
                          />
                        </div>

                        <div className="mt-3 flex items-start gap-2 rounded-lg bg-amber-50/70 border border-amber-100 p-2.5 text-xs text-amber-900">
                          <Lightbulb className="h-4 w-4 text-amber-600 shrink-0 mt-0.5" />
                          <div>
                            <span className="font-semibold">Action Plan: </span>
                            <span>{w.recommendation}</span>
                          </div>
                        </div>
                      </div>
                    ))}
                  </div>
                </div>
              )}

              {/* Proficient Subjects */}
              {report.proficientSubjects && report.proficientSubjects.length > 0 && (
                <div>
                  <h4 className="text-xs font-bold uppercase tracking-wider text-slate-700 mb-3 flex items-center gap-1.5">
                    <Trophy className="h-4 w-4 text-emerald-500" />
                    Proficient Subjects (≥ 60 Marks)
                  </h4>
                  <div className="grid grid-cols-1 sm:grid-cols-2 gap-2.5">
                    {report.proficientSubjects.map((p) => (
                      <div
                        key={p.subject}
                        className="flex items-center justify-between rounded-lg border border-slate-200 bg-slate-50/60 p-3"
                      >
                        <span className="text-xs font-semibold text-slate-800">{p.subject}</span>
                        <span className="font-mono text-xs font-bold text-emerald-700 bg-emerald-50 border border-emerald-200 px-2 py-0.5 rounded">
                          {p.mark} / 100
                        </span>
                      </div>
                    ))}
                  </div>
                </div>
              )}
            </div>
          )}
        </div>

        {/* Footer */}
        <div className="flex items-center justify-between border-t border-slate-100 bg-slate-50/70 px-6 py-4 print:hidden">
          <div className="text-[11px] text-slate-500">
            Rule: Marks &lt; 60 triggers mandatory student improvement advisory
          </div>
          <div className="flex items-center gap-2">
            <button
              onClick={handlePrint}
              className="flex items-center gap-1.5 rounded-xl border border-slate-300 bg-white px-3.5 py-1.5 text-xs font-semibold text-slate-700 hover:bg-slate-50 transition-colors"
            >
              <Printer className="h-3.5 w-3.5" />
              <span>Print Slip</span>
            </button>
            <button
              onClick={onClose}
              className="rounded-xl bg-slate-900 px-4 py-1.5 text-xs font-semibold text-white hover:bg-slate-800 transition-colors"
            >
              Close
            </button>
          </div>
        </div>
      </div>
    </div>
  );
};
